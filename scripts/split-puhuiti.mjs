/*
 * Splits the Alibaba PuHuiTi 3.0 weights into unicode-range chunks with
 * cn-font-split and writes a single aggregated CSS entry to
 * public/fonts/puhuiti/puhuiti.css. Run from the repo root:
 *
 *   node scripts/split-puhuiti.mjs <dir-with-source-woff2>
 *
 * Source files are the official woff2 downloads from
 * fonts.alibabadesign.com (the CDN needs a browser User-Agent and a
 * www.alibabafonts.com Referer) and are NOT committed:
 *
 *   AlibabaPuHuiTi-3-55-Regular.woff2   -> weight 400
 *   AlibabaPuHuiTi-3-65-Medium.woff2    -> weight 500
 *   AlibabaPuHuiTi-3-75-SemiBold.woff2  -> weight 600
 *   AlibabaPuHuiTi-3-85-Bold.woff2      -> weight 700
 */
import { readFile, mkdir, writeFile, rm } from "node:fs/promises";
import path from "node:path";
import { fontSplit } from "cn-font-split";

const srcDir = process.argv[2];
if (!srcDir) {
  console.error("usage: node scripts/split-puhuiti.mjs <dir-with-source-woff2>");
  process.exit(1);
}

const weights = [
  { file: "AlibabaPuHuiTi-3-55-Regular.woff2", weight: 400 },
  { file: "AlibabaPuHuiTi-3-65-Medium.woff2", weight: 500 },
  { file: "AlibabaPuHuiTi-3-75-SemiBold.woff2", weight: 600 },
  { file: "AlibabaPuHuiTi-3-85-Bold.woff2", weight: 700 },
];

const publicRoot = path.resolve("public/fonts/puhuiti");
await mkdir(publicRoot, { recursive: true });
const cssParts = [];

for (const { file, weight } of weights) {
  const outDir = path.join(publicRoot, String(weight));
  await rm(outDir, { recursive: true, force: true });
  console.log(`splitting ${file} -> ${path.relative(process.cwd(), outDir)}`);
  await fontSplit({
    input: new Uint8Array(await readFile(path.join(srcDir, file))),
    outDir,
    css: {
      fontFamily: "Alibaba PuHuiTi 3.0",
      fontWeight: String(weight),
      fontDisplay: "swap",
      commentUnicodes: false,
      compress: true,
    },
    renameOutputFont: "[hash:6].[ext]",
    testHtml: false,
    reporter: false,
    silent: true,
  });

  // Rewrite the generated relative urls to public paths and aggregate.
  const css = await readFile(path.join(outDir, "result.css"), "utf8");
  cssParts.push(
    `/* Alibaba PuHuiTi 3.0 — weight ${weight}, chunked by cn-font-split */\n` +
      css.replaceAll('url("./', `url("/fonts/puhuiti/${weight}/`),
  );
}

await writeFile(
  // Lives under src/app so the bundler can import it; the woff2 chunks stay
  // in public/fonts/puhuiti and are referenced by root-absolute urls.
  path.resolve("src/app/fonts/puhuiti.css"),
  `/*\n * Alibaba PuHuiTi 3.0 — generated by scripts/split-puhuiti.mjs.\n` +
    ` * Do not edit by hand; unicode-range chunks load on demand.\n */\n\n` +
    cssParts.join("\n"),
);
console.log(`wrote src/app/fonts/puhuiti.css`);
